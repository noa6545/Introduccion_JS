// == Ejercicio 1: Variables y tipos de datos basicos == //
let ciudad = "Francia";
let poblacion = 3500;
let esCapital = true;
console.log(ciudad, poblacion, esCapital);

// == Ejercicio 2: Concatenación de strings == //
let animal = "Perro";
let raza = "Labrador";
let edadAnimal = 5;
console.log("Mi " + animal + " es un " + raza + " de " + edadAnimal + " años.");
console.log("Mi", animal, "es un", raza, "de", edadAnimal, "años.");

// == Ejercicio 3: Operaciones matematicas basicas == //
let num1 = 10;
let num2 = 5;
let suma = num1 + num2;
let resta = num1 - num2;
console.log("Suma:", suma, "Resta:", resta);

// == Ejercicio 4: Uso de console.log con varias salidas == //
let nombreProducto = "Laptop";
let precio = 1200;
let disponible = true;
console.log("Producto:", nombreProducto);
console.log("Precio:", precio);
console.log("¿Esta disponible?", disponible);

// == Ejercicio 5: Concentracion y salidas separadas == //
let marcaCoche = "Toyota";
